#include <iostream>
using namespace std;

int main()
{
	float a, b, c;

	cout << "Please enter the value of first number a?" << endl;
	cin >> a;

	cout << "Please enter the value of second number b?" << endl;
	cin >> b;

	cout << "Please enter the value of third number c?" << endl;
	cin >> c;

	cout << "The sum of all numbers is: " << a + b + c << endl;

	return 0;
}