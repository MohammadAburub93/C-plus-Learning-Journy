#include <iostream>
using namespace std;

int main()
{
	cout << "The size of int data type is " << sizeof(int) << endl;
	cout << "The size of string data type is " << sizeof(string) << endl;
	cout << "The size of boolean data type is " << sizeof(bool) << endl;
	cout << "The size of float data type is " << sizeof(float) << endl;
	cout << "The size of short int data type is " << sizeof(short int) << endl;
	cout << "The size of long int data type is " << sizeof(long int) << endl;
	cout << "The size of long long int type is " << sizeof(long long int) << endl;
	cout << "The size of char data type is " << sizeof(char) << endl;
	cout << "The size of wchar_t data type is " << sizeof(wchar_t) << endl;
	

	return 0;
}