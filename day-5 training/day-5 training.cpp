#include <iostream>
using namespace std;

int main()
{
	int a, b;

	cout << "Please enter the value of the first number a?" << endl;
	cin >> a;

	cout << "Please enter the value of the second number b?" << endl;
	cin >> b;

	cout << "a + b = " << a + b << endl;
	cout << "a - b = " << a - b << endl;
	cout << "a * b = " << a * b << endl;
	cout << "a / b = " << a / b << endl;
	cout << "a % b = " << a % b << endl;

	return 0;
}